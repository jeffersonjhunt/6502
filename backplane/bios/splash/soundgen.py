#!/usr/bin/env python3
"""
soundgen.py - tables for the boot splash's sound (bootsnd.s).

Four MotoGP bikes scream past a listener at the centre of the screen, one for
each part of the logo: the O, the O and the E come in from the left as a pack,
and DIGITAL MANUFACTURING comes in from the right. Each bike is a voice played
on SID A (left) and SID B (right) at once; the lone fourth gets two more. Then
VINTAGE FAST is rubber-stamped on: bootsnd.s makes that sound itself, from the
constants here.

The model, for a bike at speed V passing at distance Y0:
  x = V t, r = sqrt(x^2 + Y0^2)
  pitch    f = f_engine(t) * C / (C + V x / r)      Doppler
  distance a = Y0 / r                             loudness
  pan      p = x / r, gains L = min(1, sqrt(1 - p)), R = min(1, sqrt(1 + p))
f_engine is the firing frequency of a 4-cylinder four-stroke (2 x rpm / 60),
climbing on the approach, with an upshift just after the pass.

The SIDs give two ways to set a level: the chip's master volume ($D418, which
pans here: SID A is left, SID B right) and each voice's sustain level, which
can be stepped down in the middle of a note. So the tables hold, per frame
since the bike started:
  PITCH  16-bit SID frequency at the NTSC clock
  SUS    the voice's sustain: 15 on the approach, sqrt(distance) after the pass
  PANL/PANR  the bike's call on each chip's master volume, 0-15
The player takes the loudest call on each chip, and on each chip routes the
bikes on the far side through a low-pass filter (the far ear hears them dull),
so each bike pans on its own even though the master volume is the chip's.
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from splashgen import PRESS_FRAMES, FRAMES, START  # noqa: E402  the splash's timing

CLOCK = 1_022_727          # the card's NTSC SID clock
FPS = 60
C, V, Y0 = 343.0, 85.0, 7.0
PRE, POST = 12, 96        # frames before and after the pass
LEN = PRE + POST
FADE = 36

# Each part starts moving at splashgen's START and is crossing the middle of
# its travel about 4 frames later. That is the pass.
PASS_AT = 4


def rpm_at(t):
    """Engine rpm t seconds from the pass: wide open, upshift at +0.14 s."""
    base = 15600 * (1 + 0.07 * (t + PRE / FPS))
    shift = 0.14
    if t < shift:
        return base
    # the shift: rpm falls to 78 % in 30 ms, then pulls again
    dt = t - shift
    drop = 0.78 + min(0.22, 0.30 * max(0.0, dt - 0.03))
    return base * drop


def tables():
    pitch, sus, panl, panr = [], [], [], []
    for i in range(LEN):
        t = (i - PRE) / FPS
        x = V * t
        r = math.hypot(x, Y0)
        f = 2 * rpm_at(t) / 60 * C / (C + V * x / r)
        a = (Y0 / r) ** 1.0
        fade = min(1.0, (LEN - 1 - i) / FADE) ** 1.5  # die away before the gate drops
        a *= max(fade, 0.0)
        p = x / r
        gl, gr = min(1.0, math.sqrt(1 - p)), min(1.0, math.sqrt(1 + p))
        pitch.append(min(0xFFFF, round(f * 16777216 / CLOCK)))
        if t < 0:
            s, level = 15, a
        else:
            # going away: half the fall (in dB) on the voice, half on the chip
            s, level = max(0, round(15 * math.sqrt(a))), math.sqrt(a)
        sus.append(s)
        panl.append(max(0, min(15, round(15 * gl * level))))
        panr.append(max(0, min(15, round(15 * gr * level))))
    # the sustain may only fall (a SID can't raise it mid-note)
    for i in range(1, LEN):
        sus[i] = min(sus[i], sus[i - 1])
    return pitch, sus, panl, panr


# The engine voices: one per bike, plus, for the bike that passes alone
# (DIGITAL MANUFACTURING), a sawtooth an octave down for body and a noise roar
# whose brightness follows its pitch. name, voice, detune, flags, and frames
# in: a layer that starts late picks up its bike's tables where they are.
RIGHT, BODY, WIND, MAIN = 0x01, 0x02, 0x04, 0x08
VOICES = [
    ("O1", 0, 0, MAIN, 0),
    ("O2", 1, +260, MAIN, 0),
    ("E", 2, -220, MAIN, 0),
    ("WORD", 0, -520, MAIN | RIGHT, 0),
    ("WORD", 1, -520, BODY | RIGHT, 8),
    ("WORD", 2, 0, WIND | RIGHT, 8),
]
SHIFT = PRE + 8                     # the upshift's frame: the quickshifter's crack

# The stamp (splashgen): a push of air as it comes down, then the thunk.
WHOOSH = START["STAMP"]
IMPACT = START["STAMP"] + PRESS_FRAMES


def reg(hz):
    return round(hz * 16777216 / CLOCK)


def main(out):
    pitch, sus, panl, panr = tables()
    lines = [
        "; Generated by soundgen.py. Do not edit.",
        f"FRAMES = {FRAMES}",
        f"LEN = {LEN}",
        f"PRE = {PRE}",
        f"SHIFT = {SHIFT}",
        f"WHOOSH = {WHOOSH}",
        f"IMPACT = {IMPACT}",
        f"NVOICES = {len(VOICES)}",
        f"RIGHT = ${RIGHT:02X}",
        f"BODY = ${BODY:02X}",
        f"WIND = ${WIND:02X}",
        f"MAIN = ${MAIN:02X}",
        f"THUMP_HZ = ${reg(120):04X}       ; 120 Hz, falling to 35",
        f"THUMP_FLOOR = ${reg(35):04X}",
        f"KNOCK_A = ${reg(196):04X}         ; the handle's wooden knock, 196 Hz left ...",
        f"KNOCK_B = ${reg(203):04X}         ; ... and 203 Hz right, a little wide",
        "SMACK_HZ = $2400",
        "SMACK_FLOOR = $0600",
        "WHOOSH_HZ = $0C00",
        "WHOOSH_STEP = $0900",
        "",
        "pitch_lo: .byte " + ",".join(f"${p & 255:02X}" for p in pitch),
        "pitch_hi: .byte " + ",".join(f"${p >> 8:02X}" for p in pitch),
        "; sustain in the high nibble",
        "sus_tab:  .byte " + ",".join(f"${s << 4:02X}" for s in sus),
        "; left call in the high nibble, right in the low",
        "pan_tab:  .byte " + ",".join(f"${l << 4 | r:02X}" for l, r in zip(panl, panr)),
        "",
        "; per engine voice: first frame, table frame it starts on, voice (index, bit,",
        "; register offset), detune, flags",
    ]
    starts = [START[v[0]] + PASS_AT - PRE + v[4] for v in VOICES]
    assert min(starts) >= 0, starts
    assert max(p << 1 for p in pitch) + 600 < 0x10000  # the roar's doubled pitch fits
    lines.append("ent_t0:  .byte " + ",".join(str(s) for s in starts))
    lines.append("ent_i0:  .byte " + ",".join(str(v[4]) for v in VOICES))
    lines.append("ent_vi:  .byte " + ",".join(str(v[1]) for v in VOICES))
    lines.append("ent_vb:  .byte " + ",".join(str(1 << v[1]) for v in VOICES))
    lines.append("ent_vo:  .byte " + ",".join(str(7 * v[1]) for v in VOICES))
    lines.append("ent_dlo: .byte " + ",".join(f"<({v[2]})" for v in VOICES))
    lines.append("ent_dhi: .byte " + ",".join(f">({v[2]})" for v in VOICES))
    lines.append("ent_fl:  .byte " + ",".join(f"${v[3]:02X}" for v in VOICES))
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"tables: {LEN} frames; pitch {min(pitch) * CLOCK / 16777216:.0f}-{max(pitch) * CLOCK / 16777216:.0f} Hz; "
          f"voices start {starts}; whoosh {WHOOSH}, impact {IMPACT}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "tables.inc")
