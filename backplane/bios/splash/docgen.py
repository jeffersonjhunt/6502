#!/usr/bin/env python3
"""
docgen.py - tables for the boot splash's ES5503 player (docsnd.s), on sound
card revision 2.

The same four bikes as the SID tune (soundgen.py's physics: Doppler, distance
and pan, the same timing), with the rpm of the recording the engine is
measured from (rpm_at, below), each the sampled engine (docsamples.py) on
oscillators in each ear, so every bike pans on its own:

  PITCH       the oscillators' frequency for the engine's table: 512 plays it
              a sample a step, whose firing frequency is docsamples.F0; it's
              oversampled, so a bike is near 512 x OVERSAMPLE
  VOL_L/R     each ear's volume, 0-255: the distance (Y0 / r) and an
              equal-power pan, with the ignition cut at the upshift (the
              quickshifter's crack plays then) and a fade at the end

Oscillators (24 enabled, 34,419 Hz). A voice peaks at 1/8 of the card's
bus, which mixes the ES5503 at a half, so each bike's engine is two
oscillators to an ear, together, for 6 dB more (even ones left, odd right):

   0-3   O1      4-7   O2      8-11  E       12-15 DIGITAL MANUFACTURING
   16-17 its body (the engine an octave down, at a single pair: half level)
   18-19 its roar (the wind loop)
   20-21 the crack (a one-shot, retriggered at each bike's upshift)
   22-23 the stamp's push of air (a one-shot)
  At the landing 0-19 play the thunk, ten to an ear, and the rest stop.
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import docsamples as ds  # noqa: E402
from soundgen import (C, FADE, FPS, IMPACT, LEN, PASS_AT, PRE, SHIFT, START, V, WHOOSH, Y0,  # noqa: E402
                      FRAMES)

# The engine's rpm, as the Mugello recording has it (docsamples.py): flat out
# in a tall gear, climbing about 9 % a second; at each upshift the
# quickshifter's cut and a drop of 11 % in a frame, then the climb again.
# The first upshift is just after the pass (SHIFT, with the crack); the
# second as the bike goes away (SHIFT2, too far off to hear its crack).
RPM_START = 17300           # at the table's first frame
CLIMB = 0.09                # a second, as a fraction
DROP = 0.89                 # an upshift
SHIFT2 = PRE + 81           # 1.35 s after the pass


def rpm_at(t):
    """Engine rpm t seconds from the pass."""
    rpm = RPM_START
    s = -PRE / FPS
    for shift in ((SHIFT - PRE) / FPS, (SHIFT2 - PRE) / FPS):
        if t < shift:
            break
        rpm *= (1 + CLIMB * (shift - s)) * DROP
        s = shift
    return rpm * (1 + CLIMB * (t - s))

RIGHT, BODY, WIND, MAIN = 0x01, 0x02, 0x04, 0x08
# name, voice (its oscillators are 2v and 2v+1), detune in PITCH units, flags, frames in
VOICES = [
    ("O1", 0, 0, MAIN, 0),
    ("O2", 1, +48, MAIN, 0),
    ("E", 2, -40, MAIN, 0),
    ("WORD", 3, -96, MAIN | RIGHT, 0),
    ("WORD", 4, -96, BODY | RIGHT, 8),
    ("WORD", 5, 0, WIND | RIGHT, 8),
]
CUT = {SHIFT: 0.35, SHIFT + 1: 0.45, SHIFT + 2: 0.8,   # the ignition cut, frame by frame
       SHIFT2: 0.45, SHIFT2 + 1: 0.8}


def tables():
    pitch, vl, vr = [], [], []
    for i in range(LEN):
        t = (i - PRE) / FPS
        x = V * t
        r = math.hypot(x, Y0)
        f = 2 * rpm_at(t) / 60 * C / (C + V * x / r)
        a = min(1.0, Y0 / r) * max(0.0, min(1.0, (LEN - 1 - i) / FADE)) ** 1.5
        a *= CUT.get(i, 1.0)
        p = x / r
        gl, gr = math.sqrt((1 - p) / 2), math.sqrt((1 + p) / 2)
        pitch.append(round(512 * f / ds.F0))
        vl.append(min(255, round(255 * a * gl * math.sqrt(2))))
        vr.append(min(255, round(255 * a * gr * math.sqrt(2))))
    return pitch, vl, vr


def table_reg(size, bank=0, resolution=7):
    return bank << 6 | ds.table_code(size) << 3 | resolution


def main(out):
    pitch, vl, vr = tables()
    assert max(pitch) * 2 + 64 < 0x10000
    starts = [START[v[0]] + PASS_AT - PRE + v[4] for v in VOICES]
    assert min(starts) >= 0 and all(v[1] == i for i, v in enumerate(VOICES))
    lines = [
        "; Generated by docgen.py. Do not edit.",
        f"FRAMES = {FRAMES}",
        f"LEN = {LEN}",
        f"SHIFT = {SHIFT}",
        f"WHOOSH = {WHOOSH}",
        f"IMPACT = {IMPACT}",
        f"NVOICES = {len(VOICES)}",
        f"RIGHT = ${RIGHT:02X}",
        f"BODY = ${BODY:02X}",
        f"WIND = ${WIND:02X}",
        f"MAIN = ${MAIN:02X}",
        f"OSCS = {ds.OSCILLATORS}",
        "; the tables: the table register (bank, size, resolution 7) and the pointer",
        f"T_ENGINE = ${table_reg(ds.ENGINE_SIZE):02X}",
        f"P_ENGINE = ${ds.ENGINE_AT >> 8 & 0xFF:02X}",
        f"T_WIND = ${table_reg(ds.WIND_SIZE):02X}",
        f"P_WIND = ${ds.WIND_AT >> 8 & 0xFF:02X}",
        f"T_CRACK = ${table_reg(ds.CRACK_SIZE):02X}",
        f"P_CRACK = ${ds.CRACK_AT >> 8 & 0xFF:02X}",
        f"T_PUSH = ${table_reg(ds.PUSH_SIZE):02X}",
        f"P_PUSH = ${ds.PUSH_AT >> 8 & 0xFF:02X}",
        f"T_THUNK_L = ${table_reg(ds.THUNK_SIZE, bank=ds.THUNK_L_AT >> 16):02X}",
        f"P_THUNK_L = ${ds.THUNK_L_AT >> 8 & 0xFF:02X}",
        f"T_THUNK_R = ${table_reg(ds.THUNK_SIZE, bank=ds.THUNK_R_AT >> 16):02X}",
        f"P_THUNK_R = ${ds.THUNK_R_AT >> 8 & 0xFF:02X}",
        "; a one-shot at one sample a step is frequency 2^(9 + resolution - size code);",
        "; the half-rate ones (push, thunk) at half that",
        f"F_CRACK = ${1 << (9 + 7 - ds.table_code(ds.CRACK_SIZE)):04X}",
        f"F_PUSH = ${1 << (8 + 7 - ds.table_code(ds.PUSH_SIZE)):04X}",
        f"F_THUNK = ${1 << (8 + 7 - ds.table_code(ds.THUNK_SIZE)):04X}",
        "; the crack's volumes, the bike's just before its cut, from the left (swapped from the right)",
        f"CRACK_VL = {vl[SHIFT - 1]}",
        f"CRACK_VR = {vr[SHIFT - 1]}",
        "",
        "pitch_lo: .byte " + ",".join(f"${p & 255:02X}" for p in pitch),
        "pitch_hi: .byte " + ",".join(f"${p >> 8:02X}" for p in pitch),
        "; volumes at half scale (0-127): the player keeps them as 7.8 fixed point",
        "vol_l:    .byte " + ",".join(str(v >> 1) for v in vl),
        "vol_r:    .byte " + ",".join(str(v >> 1) for v in vr),
        "",
        "; per voice: first frame, table frame it starts on, detune, flags",
        "ent_t0:  .byte " + ",".join(str(s) for s in starts),
        "ent_i0:  .byte " + ",".join(str(v[4]) for v in VOICES),
        "ent_dlo: .byte " + ",".join(f"<({v[2]})" for v in VOICES),
        "ent_dhi: .byte " + ",".join(f">({v[2]})" for v in VOICES),
        "ent_fl:  .byte " + ",".join(f"${v[3]:02X}" for v in VOICES),
    ]
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"doc tables: {LEN} frames; pitch {min(pitch)}-{max(pitch)} (512 = {ds.F0:.0f} Hz); voices start {starts}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "doctables.inc")
