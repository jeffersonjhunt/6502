#!/usr/bin/env python3
"""The sound card's flash, revision 3, as the emulator has it: emulator/components/devices/include/sound_flash.h.

The boot sound's samples (tools/sndflash/wave.bin, wave RAM's image from address 0) and its sequence's tables
and constants (tools/sndflash/doctables.inc), both made by backplane/bios/splash's docsamples.py and docgen.py,
which the card's firmware plays (sound_fw.cpp, BootSound) as revision 2's 6510 player played them (the ROM's
splash/docsnd.s until revision 3): the same samples and the same sequence, on the firmware's own clock
(hw/design.md, "The splash's sound": the owner's answer 12 on the build).

    python3 -I tools/mksndflash.py            # writes the header
    python3 -I tools/mksndflash.py --check    # fails if the header isn't what the sources make
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "sndflash")
OUT = os.path.join(ROOT, "emulator", "components", "devices", "include", "sound_flash.h")
BELL_HZ, BELL_MS, BELL_VOLUME = 880, 120, 96  # the bell: an A, an eighth of a second, under the beep


def tables(path):
    """doctables.inc: its NAME = value constants and its `name: .byte ...` rows."""
    consts, rows = {}, {}
    for line in open(path, encoding="ascii"):
        line = line.split(";", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"^([A-Z_][A-Z0-9_]*)\s*=\s*(\$?[0-9A-Fa-f]+)$", line)
        if m:
            v = m.group(2)
            consts[m.group(1)] = int(v[1:], 16) if v.startswith("$") else int(v)
            continue
        m = re.match(r"^([a-z_0-9]+):\s*\.byte\s+(.*)$", line)
        if m:
            out = []
            for item in m.group(2).split(","):
                item = item.strip()
                lo = re.match(r"^([<>])\((-?\d+)\)$", item)
                if lo:
                    n = int(lo.group(2)) & 0xFFFF
                    out.append(n & 0xFF if lo.group(1) == "<" else n >> 8)
                elif item.startswith("$"):
                    out.append(int(item[1:], 16))
                else:
                    out.append(int(item))
            rows[m.group(1)] = out
            continue
        raise SystemExit(f"mksndflash.py: {path}: can't read: {line}")
    return consts, rows


def header():
    wave = open(os.path.join(SRC, "wave.bin"), "rb").read()
    consts, rows = tables(os.path.join(SRC, "doctables.inc"))
    out = [
        "// Generated by tools/mksndflash.py from tools/sndflash/wave.bin and doctables.inc. Do not edit.",
        "// The sound card's flash, revision 3: the boot sound's samples and sequence (hw/design.md, \"Sound card revision 3\").",
        "#pragma once",
        "#include <cstdint>",
        "namespace ooe::emu::sound_flash",
        "{",
    ]
    for name in sorted(consts):
        out.append(f"    inline constexpr unsigned {name} = {consts[name]};")
    for name in sorted(rows):
        vals = ", ".join(str(v) for v in rows[name])
        out.append(f"    inline constexpr uint8_t {name}[{len(rows[name])}] = {{{vals}}};")
    out.append("    // the console's bell (BELL): a tone of the tone generator's")
    out.append(f"    inline constexpr unsigned BELL_HZ = {BELL_HZ}, BELL_MS = {BELL_MS}, BELL_VOLUME = {BELL_VOLUME};")
    out.append(f"    inline constexpr unsigned WAVE_SIZE = {len(wave)};")
    out.append("    inline constexpr uint8_t WAVE[WAVE_SIZE] = {")
    for i in range(0, len(wave), 16):
        out.append("        " + ", ".join(f"0x{b:02X}" for b in wave[i:i + 16]) + ",")
    out.append("    };")
    out.append("} // namespace ooe::emu::sound_flash")
    return "\n".join(out) + "\n"


def main():
    text = header()
    if sys.argv[1:] == ["--check"]:
        have = open(OUT, encoding="ascii").read() if os.path.exists(OUT) else ""
        if have != text:
            raise SystemExit("mksndflash.py: sound_flash.h is stale: run tools/mksndflash.py")
        return
    if sys.argv[1:]:
        raise SystemExit("usage: mksndflash.py [--check]")
    with open(OUT, "w", encoding="ascii") as f:
        f.write(text)


if __name__ == "__main__":
    main()
